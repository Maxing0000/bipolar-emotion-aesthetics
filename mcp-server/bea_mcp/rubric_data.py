def format_rubric(category: str, weights: dict) -> str:
    """生成某品类的完整评分标尺文本（供 AI 看图打分）。"""
    rub = RUBRICS.get(category)
    if not rub:
        raise ValueError(f"未知品类 {category!r}，可选：{'/'.join(RUBRICS)}")
    lines = [
        f"【{category} 品类 · BEA 视觉评分标尺】",
        "用法：对照图像，逐维度找到最接近的锚点描述，取该锚点的 t 值；",
        "介于两锚点之间可插值（如 3、4、6、7）。全部维度评完后，",
        "把结果交给 bea_wt_calc 算 W(T)，再用 bea_prescribe 出改进处方。",
        "评分纪律：只评「形式」本身，不评品牌好恶与价格档位。",
        "",
    ]
    for dim, w in weights.items():
        r = rub[dim]
        lines.append(f"◆ {dim}（权重 {w}）")
        lines.append(f"  观察点：{r['look']}")
        for t in (2, 5, 8):
            lines.append(f"  t={t}：{r['anchors'][t]}")
        lines.append("")
    return "\n".join(lines).rstrip()

