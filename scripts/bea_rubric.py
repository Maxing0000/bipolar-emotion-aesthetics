def format_rubric(category: str, weights: dict = None) -> str:
    """生成某品类的完整评分标尺文本（供 AI 看图打分）。

    weights 传引擎的 CATEGORY_WEIGHTS[category] 时会带出每维权重。
    """
    rub = RUBRICS.get(category)
    if not rub:
        raise ValueError(f"未知品类 {category!r}，可选：{'/'.join(RUBRICS)}")
    lines = [
        f"【{category} 品类 · BEA 视觉评分标尺】",
        "用法：对照图像，逐维度找到最接近的锚点描述，取该锚点的 t 值；",
        "介于两锚点之间可插值（如 3、4、6、7）。全部维度评完后，",
        "交给 bea_analyze 计算 W(T)，或用 bea_suggest 出调整方案。",
        "评分纪律：只评「形式」本身，不评品牌好恶与价格档位。",
        "",
    ]
    for dim, spec in rub.items():
        weight = weights.get(dim) if weights else None
        head = f"◆ {dim}" + (f"（权重 {weight}）" if weight is not None else "")
        lines.append(head)
        lines.append(f"  观察点：{spec['look']}")
        for t in (2, 5, 8):
            lines.append(f"  t={t}：{spec['anchors'][t]}")
        lines.append("")
    return "\n".join(lines).rstrip()


